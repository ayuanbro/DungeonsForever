local function walk(t, depth)
    if depth > 6 then return end
    for k, v in pairs(t) do
        if type(v) == "string" then
            local e = TR[v]
            if e then t[k] = e end
        elseif type(v) == "table" then
            walk(v, depth + 1)
        end
    end
end
if ns.DungeonRoute then walk(ns.DungeonRoute, 0) end
if ns.DungeonRouteNote then walk(ns.DungeonRouteNote, 0) end
