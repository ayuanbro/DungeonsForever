    ForgetMotion(GetTime())
end)

local function ShowMarker(shown)
    local marker, states = SuperTrackedFrame, Enum and Enum.NavigationState
    if type(marker) ~= "table" or not marker.SetTargetAlphaForState or not states then
        return
    end
    for name, alpha in pairs(MARKER_ALPHA) do
        if states[name] ~= nil then
            pcall(marker.SetTargetAlphaForState, marker, states[name], shown and alpha or 0)
        end
    end
end

local function Remember()
    local track = C_SuperTrack
    local state = { entries = {} }
    local function keep(kind, isSet, set)
        state.entries[#state.entries + 1] = { kind = kind, isSet = isSet, set = set }
    end

    pcall(function()
        local quest = track.GetSuperTrackedQuestID()
        if quest and quest ~= 0 then
            keep(TRACK_QUEST, function()
                return track.GetSuperTrackedQuestID() == quest
            end, function()
                track.SetSuperTrackedQuestID(quest)
            end)
        end
    end)
    pcall(function()
        if track.IsSuperTrackingUserWaypoint() then
            keep(TRACK_WAYPOINT, track.IsSuperTrackingUserWaypoint, function()
                track.SetSuperTrackedUserWaypoint(true)
            end)
        end
    end)
    pcall(function()
        local contentType, contentId = track.GetSuperTrackedContent()
        if contentType ~= nil and contentId ~= nil then
            keep(TRACK_CONTENT, function()
                local nowType, nowId = track.GetSuperTrackedContent()
                return nowType == contentType and nowId == contentId
            end, function()
                track.SetSuperTrackedContent(contentType, contentId)
            end)
        end
    end)
    pcall(function()
        local vignette = track.GetSuperTrackedVignette()
        if vignette then
            keep(TRACK_VIGNETTE, function()
                return track.GetSuperTrackedVignette() == vignette
            end, function()
                track.SetSuperTrackedVignette(vignette)
            end)
        end
    end)
    pcall(function()
        local kind, id = track.GetSuperTrackedMapPin()
        if kind ~= nil and id ~= nil and not (kind == PIN_TYPE and ours[id]) then
            keep(TRACK_PIN, function()
                local nowKind, nowId = track.GetSuperTrackedMapPin()
                return nowKind == kind and nowId == id
            end, function()
                track.SetSuperTrackedMapPin(kind, id)
            end)
        end
    end)
    pcall(function()
        state.active = track.GetHighestPrioritySuperTrackingType()
    end)
    return state
end

local function Restore(state)
    local track = C_SuperTrack
    pcall(function()
        local kind, id = track.GetSuperTrackedMapPin()
        if kind == PIN_TYPE and ours[id] then
            track.ClearSuperTrackedMapPin()
        end
    end)
    if not state then
        return
    end

    local last
    for _, entry in ipairs(state.entries) do
        if entry.kind == state.active then
            last = entry
        else
            pcall(function()
                if not entry.isSet() then
                    entry.set()
                end
            end)
        end
    end
    if last then
        pcall(function()
            if not last.isSet() then
                last.set()
            end
        end)
    end
end

function Locator.Available()
    return C_SuperTrack ~= nil and C_SuperTrack.SetSuperTrackedMapPin ~= nil and C_Navigation ~= nil
        and C_Navigation.GetDistance ~= nil and ns.PathAnchors ~= nil
end

function Locator.IsRunning()
    return running
end

function Locator.Start(mapId)
    if not Locator.Available() then
        return false
    end
    if running and runningMap == mapId then
        return true
    end
    if running then
        Locator.Stop()
    end

    local nodes = ns.PathAnchors.nodes
    local order, late = {}, {}
    for _, id in ipairs(ns.PathAnchors.maps[mapId] or ns.PathAnchors.fallback) do
        if nodes[id] then
            if deaf[id] then
                late[#late + 1] = id
            else
                order[#order + 1] = id
            end
        end
    end
    for _, id in ipairs(late) do
        order[#order + 1] = id
    end
    if #order < 4 then
        return false
    end

    anchors, ours, pool, candidates = {}, {}, {}, order
    rotated, reorderDue, confirmed, lastValueAt, interval, outranked = false, false, false, nil, 0, nil
    for index, id in ipairs(order) do
        ours[id] = true
        if index <= ACTIVE_ANCHORS then
            anchors[index] = NewAnchor(id)
        else
            pool[#pool + 1] = id
        end
    end
    saved = Remember()
    ShowMarker(false)

    local now = GetTime()
    running, runningMap = true, mapId
    acquiring, acquireStart, acquiredAt, acquireFrom, settle = true, now, 0, 0, SETTLE
    fix, heading, unsure, pending, blockedUntil = nil, nil, 0, false, 0
    misses, rejects, lastSuccess = 0, 0, 0
    ForgetMotion(now)
    for index = #heights, 1, -1 do
        heights[index] = nil
    end
    current, previous = 1, nil
    Switch(1, now)
    driver:Show()
    return true
end

function Locator.Stop()
    if not running then
        return
    end

    running, runningMap = false, nil
    driver:Hide()
    fix = nil
    Restore(saved)
    saved = nil
    ShowMarker(true)
end

function Locator.Get()
    if not running or not fix or not confirmed then
        return
    end

    local now = GetTime()
    local x, y = Estimate(now)
    return x, y, fix.height, heading, now - fix.time, math.sqrt(velocityX * velocityX + velocityY * velocityY), fix.residual
end

