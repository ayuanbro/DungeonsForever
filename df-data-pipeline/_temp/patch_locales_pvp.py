for fname, table in (('Locales/zhTW.lua', T), ('Locales/enUS.lua', E)):
    p = os.path.join(ROOT, fname)
    raw = open(p, 'rb').read().decode('utf-8')
    crlf = raw.count('\r\n') > 0
    nl = '\r\n' if crlf else '\n'
    added = 0
    lines = []
    for k, v in table.items():
        if ('L["%s"]' % k) in raw:
            continue
        lines.append('L["%s"] = "%s"' % (k, v))
        added += 1
    if lines:
        if not raw.endswith('\n'):
            raw += nl
        raw += nl + lines[0].join([''])  # no-op keep structure simple
        raw = raw + nl.join(lines) + nl
        assert raw.count('\n') - raw.count('\r\n') == (0 if crlf else raw.count('\n'))
        open(p, 'wb').write(raw.encode('utf-8'))
    print('%s: +%d entries' % (fname, added))
