# ★★ 行尾自愈：锚点/替换串按目标文件的实际行尾补齐。CRLF 文件（DungeonUI/
#    MapUI/ExploreUI/QuickBar/Hui 等手写件）的锚点若写成裸 \n，注入按原始字节
#    匹配永远 count==0 —— 而 check_mut_anchors 归一化换行后体检照样绿，烂锚
#    是静默的。此处读 titan 源文件判定行尾形态，纯 CRLF 文件的 old/new 里所有
#    裸 \n 一律补成 \r\n；LF 文件与混合行尾文件保持原样。兜住 mk_df_mut.py
#    生成器里的漏转义条目，修完生成器也不回退。
