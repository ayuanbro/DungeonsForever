def run_harness():
    r = subprocess.run([PY, os.path.join(HERE, 'df_dungeon_check.py')],
                       capture_output=True, text=True, encoding='utf-8', errors='replace')
    out = (r.stdout or '') + (r.stderr or '')
    fails = [l.strip() for l in out.splitlines() if '[FAIL]' in l]
    tail = [l.strip() for l in out.splitlines() if l.strip().startswith('通过')]
    return fails, (tail[0] if tail else None)


# ★★ 先跑一遍**未变异**的基线。harness 里可能有别的工作线留下的失败断言（并发开发时
#    常见）；不取差集的话「FAIL 数 > 0」恒成立 → 每条变异都被误判成「被抓住」，
#    整个隔离检查静默失效。只认「注入后**新出现**的 FAIL」才算抓住。
base_fails, base_tail = run_harness()
if base_fails:
    print('基线（未变异）：%s，另有 %d 条既有 FAIL 与本批无关，按差集判定'
          % (base_tail or '无汇总行', len(base_fails)))
    for l in base_fails[:8]:
        print('  · ' + l[:140])
    if len(base_fails) > 8:
        print('  …共 %d 条' % len(base_fails))
else:
    print('基线（未变异）：%s（无既有 FAIL）' % (base_tail or '无汇总行'))

bad = []
for name in sorted(specs):
    fname, old, new = specs[name]
