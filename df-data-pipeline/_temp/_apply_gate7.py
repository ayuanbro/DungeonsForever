def rep(buf, old, new, tag, style=b'\r\n'):
    n = buf.count(old)
    if n != 1:
        print('!! [%s] 锚点命中 %d 次（要求 1 次）' % (tag, n))
        sys.exit(1)
    out = buf.replace(old, new)
    # 行尾守恒：CRLF 文件里新增内容不许出现裸 LF
    bare_before = buf.count(b'\n') - buf.count(b'\r\n')
    bare_after = out.count(b'\n') - out.count(b'\r\n')
    if style == CR:
        assert bare_after == bare_before, (tag, bare_before, bare_after)
    else:
        assert bare_after > bare_before, tag
    return out


