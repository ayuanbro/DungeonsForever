# ── 通用规则（只动注释文本）──────────────────────────────────────────────────
R1 = re.compile(r'用户\s*' + DATE + r'\s*[^\s，。；）：「」]{0,8}：?')      # 用户 <date> xxx：
R2 = re.compile(DATE + r'\s*用户[^\s，。；）：「」]{0,8}：?')              # <date> 用户xxx：
TOKENS = ['用户实机拍板', '用户截图反馈', '用户实机报', '用户只要求', '用户问起后确认',
          '用户点名', '用户定稿', '用户指定', '用户口径', '用户决定', '用户明确',
          '用户拍板', '用户原话', '用户要求', '用户反馈', '用户实测', '用户截图',
          '用户报', '用户定', '用户：']
R_ROUND = re.compile(r'(?<![第上这下每先等])(?<![\u4e00-\u9fff])[一二三四五六七八九十]+轮')
R_DATE = re.compile(DATE + r'\s*起?：?')
R_DASH_END = re.compile(r'([^\s─])──\s*$')
ARTIFACTS = [('（）', ''), ('（ ）', ''), ('（：', '（'), ('（，', '（'), ('（、', '（'),
             ('（；', '（'), ('，）', '）'), ('、）', '）'), ('，  ', '，'), ('；  ', '；'),
             ('：  ', '：'), ('）  ', '）'), ('（  ', '（'),
             ('★★ ：', '★★ '), ('★ ：', '★ '), ('（ ', '（'), ('；）', '）'),
             ('； ', '；'), ('， ', '，')]
R_CJK_SP = re.compile(r'([\u4e00-\u9fff])  +(\S)')
R_SP_CJK = re.compile(r'(\S)  +([\u4e00-\u9fff])')
R_PREFIX = re.compile(r'^(\s*--+[ \t]*)')

# 这些行里的日期/「用户」是有语义的，整行跳过通用规则
KEEP_MARKS = ('标注更新日', '用户航点', '用户悬停', '用户缩放', '用户手动拖动',
              '用户常用白', '用户无感知', '用户切走', '用户只看得到', '用户不必',
              '用户看到', 'updated = ')


def clean_generic(text):
    if any(k in text for k in KEEP_MARKS):
        return text
    t0 = text
    text = R1.sub('', text)
    text = R2.sub('', text)
    for tok in TOKENS:
        text = text.replace(tok, '')
    text = R_ROUND.sub('', text)
    for tok in TOKENS:                      # 轮次删除后可能再露出「用户xx」
        text = text.replace(tok, '')
    text = R_DATE.sub('', text)
    if text == t0:
        return text                         # 行未被改过 → 不做括号/空格清理，保住原有对齐
    text = R_DASH_END.sub(r'\1 ──', text)
    for _ in range(3):
        for old, new in ARTIFACTS:
            text = text.replace(old, new)
        text = R_CJK_SP.sub(r'\1 \2', text)
        text = R_SP_CJK.sub(r'\1 \2', text)
    return text


def process(path, pairs):
    with io.open(path, 'r', encoding='utf-8', newline='') as f:
        raw = f.read()
    eol = '\r\n' if '\r\n' in raw else '\n'
    lines = raw.split(eol)

    # 1) 特例对（全行范围，字节精确）
    for old, new, *rest in pairs:
        want = rest[0] if rest else 1
        n = raw.count(old)
        if n != want:
            die('%s 特例对命中 %d 次（应为 %d）：%s' % (path, n, want, old[:60]))
        raw = raw.replace(old, new)
    lines = raw.split(eol)

    # 2) 通用规则：注释行全行；代码行的行尾注释（tail 含触发词才动）
    out = []
    for ln in lines:
        if ln.lstrip().startswith('--'):
            m = R_PREFIX.match(ln)
            if m:
                out.append(m.group(1) + clean_generic(ln[m.end():]))
            else:
                out.append(clean_generic(ln))
            continue
        idx = ln.find(' -- ')
        if idx > 0:
            head, tail = ln[:idx], ln[idx + 1:]
            if re.search(r'用户|' + DATE, tail):
                out.append(head + ' ' + clean_generic(tail))
                continue
        out.append(ln)
    new_raw = eol.join(out)
    if new_raw != raw:
        with io.open(path, 'w', encoding='utf-8', newline='') as f:
            f.write(new_raw)
    return raw, new_raw


def die(msg):
    sys.stderr.write('clean_comments: %s\n' % msg)
    sys.exit(1)


def main():
    total = 0
    for rel, pairs in sorted(SPECIALS.items()):
        path = os.path.join(ROOT, rel.replace('/', os.sep))
        old, new = process(path, pairs)
        n = sum(1 for a, b in zip(old.splitlines(), new.splitlines()) if a != b)
        total += n
        print('%-40s %3d 行变更' % (rel, n))
    print('特例文件处理完毕；下面处理纯通用文件')

    for rel in ['Core/MainFrame.lua', 'Core/Data/Data_DungeonLoot.lua']:
        path = os.path.join(ROOT, rel.replace('/', os.sep))
        old, new = process(path, [])
        n = sum(1 for a, b in zip(old.splitlines(), new.splitlines()) if a != b)
        total += n
        print('%-40s %3d 行变更' % (rel, n))
    print('完成，共 %d 行变更' % total)


if __name__ == '__main__':
    main()
