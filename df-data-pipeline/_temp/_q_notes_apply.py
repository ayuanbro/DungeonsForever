def split_fields(line):
    """切分行内顶层字段（外层 {} 内、depth==1 处的逗号），返回 [(start, end, text), ...]。"""
    assert line.lstrip().startswith('{'), 'not a row line'
    fields, depth, i, n = [], 0, 0, len(line)
    in_str, esc = False, False
    start = None
    while i < n:
        c = line[i]
        if in_str:
            if esc:
                esc = False
            elif c == '\\':
                esc = True
            elif c == '"':
                in_str = False
        else:
            if c == '"':
                in_str = True
                if depth >= 1 and start is None:
                    start = i
            elif c == '{':
                depth += 1
                if depth == 1:
                    start = i
            elif c == '}':
                depth -= 1
                if depth == 0 and start is not None:
                    fields.append((start, i + 1, line[start:i + 1]))
                    start = None
            elif c == ',' and depth == 1:
                fields.append((start, i, line[start:i] if start is not None else ''))
                start = None
            elif depth >= 1 and start is None and not c.isspace():
                start = i
        i += 1
    return fields


